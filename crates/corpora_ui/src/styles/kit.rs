pub(super) fn highlight(mode: Mode) -> gpui_kit::component::highlighter::HighlightTheme {
    use gpui_kit::component::highlighter::{
        HighlightTheme, HighlightThemeStyle, SyntaxColors, ThemeStyle,
    };
    let p = build(mode);
    let style = |color| {
        // Kit keeps ThemeStyle's fields private; its public serde format accepts colors.
        let fields = toml::Table::from_iter([(
            "color".into(),
            toml::Value::try_from(color).expect("syntax color"),
        )]);
        fields.try_into::<ThemeStyle>().expect("syntax style")
    };
    HighlightTheme {
        name: "Default".into(),
        appearance: match mode {
            Mode::Light => gpui_kit::component::ThemeMode::Light,
            Mode::Dark => gpui_kit::component::ThemeMode::Dark,
        },
        style: HighlightThemeStyle {
            editor_background: Some(p.bg),
            editor_foreground: Some(p.fg),
            editor_active_line: Some(p.hover),
            editor_line_number: Some(p.fg_muted),
            editor_active_line_number: Some(p.fg),
            editor_invisible: Some(p.fg_subtle),
            editor_gutter_background: Some(p.sunken),
            status: Default::default(),
            syntax: SyntaxColors {
                attribute: Some(style(p.syntax.attribute)),
                boolean: Some(style(p.syntax.constant)),
                comment: Some(style(p.syntax.comment)),
                comment_doc: Some(style(p.syntax.comment)),
                constant: Some(style(p.syntax.constant)),
                constructor: Some(style(p.syntax.type_name)),
                embedded: Some(style(p.syntax.variable)),
                emphasis: Some(style(p.syntax.variable)),
                emphasis_strong: Some(style(p.syntax.variable)),
                enum_: Some(style(p.syntax.type_name)),
                function: Some(style(p.syntax.function)),
                hint: Some(style(p.syntax.variable)),
                keyword: Some(style(p.syntax.keyword)),
                label: Some(style(p.syntax.attribute)),
                link_text: Some(style(p.syntax.variable)),
                link_uri: Some(style(p.syntax.variable)),
                number: Some(style(p.syntax.number)),
                operator: Some(style(p.syntax.operator)),
                predictive: Some(style(p.syntax.variable)),
                preproc: Some(style(p.syntax.keyword)),
                primary: Some(style(p.syntax.variable)),
                property: Some(style(p.syntax.property)),
                punctuation: Some(style(p.syntax.punctuation)),
                punctuation_bracket: Some(style(p.syntax.punctuation)),
                punctuation_delimiter: Some(style(p.syntax.punctuation)),
                punctuation_list_marker: Some(style(p.syntax.punctuation)),
                punctuation_special: Some(style(p.syntax.punctuation)),
                string: Some(style(p.syntax.string)),
                string_escape: Some(style(p.syntax.string)),
                string_regex: Some(style(p.syntax.string)),
                string_special: Some(style(p.syntax.string)),
                string_special_symbol: Some(style(p.syntax.string)),
                tag: Some(style(p.syntax.tag)),
                tag_doctype: Some(style(p.syntax.tag)),
                text_code_span: Some(style(p.syntax.variable)),
                text_literal: Some(style(p.syntax.variable)),
                title: Some(style(p.syntax.function)),
                type_: Some(style(p.syntax.type_name)),
                variable: Some(style(p.syntax.variable)),
                variable_special: Some(style(p.syntax.variable)),
                variant: Some(style(p.syntax.constant)),
            },
        },
    }
}
